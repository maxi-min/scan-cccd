import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "build-env");
const outFile = path.join(outDir, "app.env");
const strict = process.argv.includes("--strict");

const PLACEHOLDER_KEYS = new Set(["MY_GEMINI_API_KEY", ""]);

function parseEnvFile(content) {
  const result = {};
  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    result[key] = value;
  }
  return result;
}

function loadEnvVars() {
  const merged = {};
  for (const file of [".env.build", ".env", ".env.local"]) {
    const filePath = path.join(root, file);
    if (!fs.existsSync(filePath)) continue;
    Object.assign(merged, parseEnvFile(fs.readFileSync(filePath, "utf8")));
  }
  if (process.env.GEMINI_API_KEY) merged.GEMINI_API_KEY = process.env.GEMINI_API_KEY;
  if (process.env.APP_URL) merged.APP_URL = process.env.APP_URL;
  return merged;
}

function formatEnvFile(vars) {
  const lines = [
    "# Generated by scripts/prepare-build-env.mjs (bundled into Windows installer)",
    `# Built at: ${new Date().toISOString()}`,
    "",
  ];
  if (vars.GEMINI_API_KEY) {
    lines.push(`GEMINI_API_KEY="${vars.GEMINI_API_KEY.replace(/"/g, '\\"')}"`);
  }
  if (vars.APP_URL) {
    lines.push(`APP_URL="${vars.APP_URL.replace(/"/g, '\\"')}"`);
  }
  return `${lines.join("\n")}\n`;
}

function removeBundledEnv() {
  if (fs.existsSync(outFile)) fs.unlinkSync(outFile);
}

const vars = loadEnvVars();
const apiKey = vars.GEMINI_API_KEY?.trim();
const hasKey = apiKey && !PLACEHOLDER_KEYS.has(apiKey);

if (!hasKey) {
  removeBundledEnv();
  const msg =
    "Không tìm thấy GEMINI_API_KEY hợp lệ (.env.build, .env hoặc biến môi trường).";
  if (strict) {
    console.error(`❌ ${msg}`);
    console.error("   Tạo .env.build (xem .env.build.example) hoặc export GEMINI_API_KEY=...");
    process.exit(1);
  }
  console.warn(`⚠️  ${msg} — installer sẽ không nhúng .env.`);
  if (process.env.CI === "true") {
    console.warn(
      "   CI: Thêm repository secret GEMINI_API_KEY tại GitHub → Settings → Secrets and variables → Actions."
    );
  }
  process.exit(0);
}

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, formatEnvFile(vars));
console.log("✓ Đã tạo build-env/app.env — sẽ được đóng gói vào file cài đặt (.exe)");
